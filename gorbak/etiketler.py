def etiket_adi(eleman) -> str:
    anahtar = getattr(eleman, "keyword", "") or ""
    if anahtar in TURKCE:
        return TURKCE[anahtar]
    ad = getattr(eleman, "name", "") or anahtar
    if eleman.tag.is_private:
        return f"Özel etiket · {ad}" if ad and ad != "Private tag data" else "Özel etiket"
    return ad
